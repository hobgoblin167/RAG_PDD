def parse_appendix(text, start_marker, end_marker=None, num_pattern=r'^(?P<num>[\d.]+(?:-[\.\d]+)?)\s+[—–-]?\s*'):
    """Универсальный парсер для приложений по номерам в начале строк."""
    start = text.find(start_marker)
    if start == -1:
        return []
    if end_marker:
        end = text.find(end_marker, start)
        if end == -1:
            end = len(text)
    else:
        end = len(text)
    sub = text[start:end]
    pattern = re.compile(num_pattern, re.MULTILINE)
    matches = list(pattern.finditer(sub))
    chunks = []
    for i, m in enumerate(matches):
        start_pos = m.start()
        end_pos = matches[i+1].start() if i+1 < len(matches) else len(sub)
