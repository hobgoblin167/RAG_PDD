def rag_pipeline(query, index, chunks, embedding_model, llm, top_k=5):
    """Полный пайплайн RAG: поиск + генерация"""
    retrieved = retrieve(query, index, chunks, embedding_model, top_k)
    answer = generate_answer(query, retrieved, llm)
    return answer, retrieved

