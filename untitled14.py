def generate_answer(query, retrieved_chunks, llm):
    """Генерирует ответ на основе найденных чанков."""
    # Формируем контекст
    context_parts = []
    for i, res in enumerate(retrieved_chunks):
        chunk = res['chunk']

        # Формируем заголовок в зависимости от типа чанка
        if chunk.get('term'):
            header = f"Термин \"{chunk['term']}\""
        elif chunk.get('chapter'):
            header = f"{chunk['chapter']} (пункт {chunk['point']})"
        elif chunk.get('section'):
            header = f"{chunk['section']} (пункт {chunk['point']})"
        else:
            header = "Информация"

        context_parts.append(f"{header}:\n{chunk['text']}")

    context = "\n\n".join(context_parts)

    system_prompt = """
Ты — эксперт по правилам дорожного движения (ПДД) Российской Федерации.
Правила ответа:
1. Используй ТОЛЬКО информацию из предоставленного контекста.
2. Если в контексте нет ответа — скажи "В предоставленном контексте нет информации об этом".
3. Отвечай подробно и развернуто, объясняя все нюансы.
4. Всегда указывай конкретные пункты ПДД (например, "пункт 1.3 ПДД").
5. Если есть исключения — обязательно их перечисли

Важно! Различай:
- Пункты ПДД (нумерация 1.1, 1.2... в основной части)
- Номера дорожной разметки (1.1, 1.2... в Приложении 2)

При ответе о разметке:
- Сплошные линии (1.1, 1.2, 1.3): пересекать запрещено
- Прерывистые линии (1.5, 1.6, 1.7, 1.8): пересекать разрешено
- Комбинированная (1.11): со стороны прерывистой - можно, со стороны сплошной - только при завершении обгона
- Линию 1.2 можно пересекать только для остановки на обочине

Всегда указывай, откуда информация: "Согласно Приложению 2 ПДД..." или "Согласно пункту X ПДД..."
"""

    user_prompt = f"""Контекст для ответа (информация из ПДД):
{context}

Вопрос пользователя: {query}

Ответ:"""

